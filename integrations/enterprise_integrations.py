def format_slack_blocks(report_markdown: str, incident_title: str, severity: str = "P1") -> dict:
    """
    Format post-mortem executive brief and risk matrix as Slack Block Kit JSON.
    Teams can directly post this into their #incident-* Slack channels.
    """
    # Extract executive summary
    lines = report_markdown.split("\n")
    exec_summary = ""
    in_exec = False
    for line in lines:
        if "## Executive Summary" in line:
            in_exec = True
            continue
        if in_exec and line.startswith("##"):
            break
        if in_exec and line.strip():
            exec_summary += line.strip() + " "

    if not exec_summary:
        exec_summary = "Incident resolved. Post-mortem report generated."

    blocks = [
        {
            "type": "header",
            "text": {
                "type": "plain_text",
                "text": f"Post-Mortem: {incident_title}",
                "emoji": False,
            },
        },
        {
            "type": "section",
            "fields": [
                {"type": "mrkdwn", "text": f"*Severity:*\n`{severity}`"},
                {"type": "mrkdwn", "text": "*Status:*\n`Resolved & Verified`"},
            ],
        },
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Executive Summary:*\n{exec_summary[:500]}",
            },
        },
        {"type": "divider"},
        {
            "type": "context",
            "elements": [
                {
                    "type": "mrkdwn",
                    "text": "_Generated by Agentic Incident Post-Mortem Engine | Blameless & Evidence-Grounded_",
                }
            ],
        },
    ]
    return {"blocks": blocks}


def export_jira_tickets(report_markdown: str) -> list[dict]:
    """
    Parse Action Items table from the markdown report and generate Jira ticket payloads.
    """
    import re
    tickets = []
    
    # Regex to extract action items table rows: | Priority | Type | Action | Owner | Est. |
    table_match = re.search(r"##\s*(?:<img[^>]*>\s*)?Action Items\s*\n(.*?)(?=\n##|\Z)", report_markdown, re.DOTALL | re.IGNORECASE)
    if not table_match:
        # Fallback search for any header containing Action Items
        table_match = re.search(r"##.*Action Items.*?\n(.*?)(?=\n##|\Z)", report_markdown, re.DOTALL | re.IGNORECASE)

    if table_match:
        table_text = table_match.group(1).strip()
        rows = [r for r in table_text.split("\n") if r.strip().startswith("|") and "---" not in r]
        
        for row in rows[1:]:  # skip header
            cols = [c.strip().replace("**", "") for c in row.split("|")[1:-1]]
            if len(cols) >= 3:
                priority = cols[0]
                action_type = cols[1] if len(cols) > 1 else "Task"
                summary = cols[2] if len(cols) > 2 else "Action Item"
                owner = cols[3] if len(cols) > 3 else "Unassigned"
                
                tickets.append({
                    "project": {"key": "INC"},
                    "issuetype": {"name": "Task"},
                    "summary": f"[{priority}] [{action_type.capitalize()}] {summary}",
                    "description": f"Automated post-mortem action item.\nType: {action_type}\nOwner: {owner}",
                    "priority": {"name": "High" if "P0" in priority or "P1" in priority else "Medium"},
                    "labels": ["postmortem", "incident-action-item", action_type.lower()],
                })
    return tickets


def handle_pagerduty_webhook(payload: dict) -> dict:
    """
    Handle incoming PagerDuty incident resolution webhook.
    Returns the auto-generated post-mortem trigger command.
    """
    event = payload.get("event", {})
    incident = event.get("data", {})
    incident_id = incident.get("id", "INC-UNKNOWN")
    title = incident.get("title", "Service Outage")
    
    return {
        "status": "triggered",
        "incident_id": incident_id,
        "title": title,
        "message": f"Post-mortem generation started for {title} ({incident_id})",
    }


def main():
    parser = argparse.ArgumentParser(description="Zero-Friction Enterprise Integration CLI")
    parser.add_argument("--incident-dir", required=True, help="Directory containing incident artifacts")
    parser.add_argument("--export-slack", action="store_true", help="Generate Slack Block Kit payload")
    parser.add_argument("--export-jira", action="store_true", help="Extract and output Jira action item tickets")
    parser.add_argument("--output", default=None, help="Save report to specified output path")
    args = parser.parse_args()

    result = run_pipeline(args.incident_dir, verbose=True)
    report_md = result.get("report_markdown", "")
    title = result.get("incident_title", "Incident")

    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(report_md)
        print(f"Report saved to {args.output}")

    if args.export_slack:
        slack_payload = format_slack_blocks(report_md, title)
        print("\n--- SLACK BLOCK KIT PAYLOAD ---")
        print(json.dumps(slack_payload, indent=2))

    if args.export_jira:
        jira_tickets = export_jira_tickets(report_md)
        print("\n--- JIRA ACTION ITEM TICKETS ---")
        print(json.dumps(jira_tickets, indent=2))


if __name__ == "__main__":
    main()
